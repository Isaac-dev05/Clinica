const { readFileSync } = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = vm.createContext({ document: { addEventListener() {} } });
vm.runInContext(readFileSync('SITE/html/clinic.js', 'utf8'), context);
const evaluate = expression => vm.runInContext(expression, context);
const now = 'new Date(2026, 10, 13, 10, 15)';
assert.equal(evaluate(`slotsFor('2026-11-12', ${now}).length`), 0);
assert.equal(evaluate(`slotsFor('2026-11-15', ${now}).length`), 0);
assert.equal(evaluate(`slotsFor('2026-11-14', ${now}).length`), 8);
assert.equal(evaluate(`slotsFor('2026-11-16', ${now}).length`), 20);
assert.equal(evaluate(`slotsFor('2026-11-13', ${now})[0]`), '10:30');
assert.equal(evaluate(`slotsFor('2026-11-13', new Date(2026, 10, 13, 18)).length`), 0);
assert.equal(evaluate(`slotsFor('2026-02-30', new Date(2026, 0, 1)).length`), 0);
assert.equal(evaluate(`slotsFor('invalid', ${now}).length`), 0);
assert.equal(evaluate(`slotsFor('2026-11-14', ${now}).at(-1)`), '11:30');
